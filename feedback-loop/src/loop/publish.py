"""Publish a digest to the static site (GitHub Pages serves `docs/`): the digest page, an index, and an RSS feed."""

import re
from datetime import UTC, date, datetime
from email.utils import format_datetime
from pathlib import Path
from xml.sax.saxutils import escape

FEED_ITEMS = 20
_DIGEST_NAME = re.compile(r"^(\d{4}-\d{2}-\d{2})\.md$")


def publish(digest_md: str, site: Path, week_ending: date, *, site_url: str, title: str = "Loop digest") -> Path:
    """Write site/digests/<week_ending>.md, then rebuild site/index.md and site/feed.xml from every digest there.
    Re-publishing the same week overwrites that week's page, so a re-run is safe."""
    digests = site / "digests"
    digests.mkdir(parents=True, exist_ok=True)
    page = digests / f"{week_ending}.md"
    page.write_text(f"---\ntitle: \"{title}: week ending {week_ending}\"\n---\n\n{digest_md}")
    weeks = sorted((m.group(1) for p in digests.iterdir() if (m := _DIGEST_NAME.match(p.name))), reverse=True)
    _write_index(site, weeks, title)
    _write_feed(site, weeks[:FEED_ITEMS], title, site_url.rstrip("/"))
    return page


def _write_index(site: Path, weeks: list[str], title: str) -> None:
    lines = ["---", f"title: \"{title}\"", "---", "", f"# {title}", "",
             "A weekly digest of the public Claude Code issue tracker: what users ask for, what hurts them, who is "
             "blocked, and what shipped. Generated by Loop with Claude, checked in code, reviewed by a human when "
             "the checks fail. [How it works](design.html) · [RSS](feed.xml)", "",
             "Spot something wrong? Every digest row has a flag link; flags feed the review queue and the eval set.",
             "", "## Digests", ""]
    lines += [f"- [Week ending {w}](digests/{w}.html)" for w in weeks] or ["- None yet"]
    (site / "index.md").write_text("\n".join(lines) + "\n")


def _write_feed(site: Path, weeks: list[str], title: str, site_url: str) -> None:
    items = []
    for w in weeks:
        url = f"{site_url}/digests/{w}.html"
        pub = format_datetime(datetime.fromisoformat(w).replace(tzinfo=UTC))
        items.append(f"    <item>\n      <title>{escape(f'{title}: week ending {w}')}</title>\n"
                     f"      <link>{escape(url)}</link>\n      <guid isPermaLink=\"true\">{escape(url)}</guid>\n"
                     f"      <pubDate>{pub}</pubDate>\n    </item>")
    feed = ("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<rss version=\"2.0\">\n  <channel>\n"
            f"    <title>{escape(title)}</title>\n    <link>{escape(site_url + '/')}</link>\n"
            "    <description>Weekly digest of the public Claude Code issue tracker</description>\n"
            + ("\n".join(items) + "\n" if items else "") + "  </channel>\n</rss>\n")
    (site / "feed.xml").write_text(feed)
